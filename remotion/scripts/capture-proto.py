# Captures r11 prototype CSS + rendered screen markup into src/joola/proto.generated.ts
import asyncio, json
from playwright.async_api import async_playwright
P="file:///workspace/portfolio/remotion/assets/joola-b2b/B2B%20quick%20order%20prototype.html"
async def m():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path="/usr/bin/google-chrome"); pg=await b.new_page(viewport={"width":1920,"height":1080})
    await pg.goto(P); await pg.wait_for_timeout(1000)
    await pg.evaluate("(()=>{const i=document.querySelector('[data-po-input]');i.value='ENG-9812';document.querySelector('[data-place-order]').click()})()")
    css=await pg.evaluate("document.querySelector('style').textContent")
    secs=await pg.evaluate("""Object.fromEntries([...document.querySelectorAll('#app > section.screen')].map(s=>[s.dataset.screen, s.outerHTML.replace('class="screen active"','class="screen"')]))""")
    toast=await pg.evaluate("document.querySelector('[data-toast]').outerHTML")
    css=css.replace('url("fonts/','url("__A__/fonts/')
    for k in secs: secs[k]=secs[k].replace('src="products/','src="__A__/products/').replace('src="joola','src="__A__/joola').replace('src="engage','src="__A__/engage').replace('src="holabird','src="__A__/holabird')
    out="// AUTO-GENERATED by scripts/capture-proto.py from the r11 prototype HTML. Do not edit.\n"
    out+="export const PROTO_CSS = "+json.dumps(css)+";\n"
    out+="export const PROTO_SCREENS: Record<string,string> = "+json.dumps(secs,indent=0)+";\n"
    out+="export const PROTO_TOAST = "+json.dumps(toast)+";\n"
    open("src/joola/proto.generated.ts","w").write(out)
    print({k:len(v) for k,v in secs.items()})
    await b.close()
asyncio.run(m())
