// Packs scripts/data/outline-words.json (the baked nav-letter droplets) into
// two lossless, much smaller forms:
//   components/outlineMorphPacked.ts  delta + varint text the morph decodes
//   app/nav-words.css                 resting letters as CSS mask images, so
//                                     they ship in the cached, render-blocking
//                                     stylesheet instead of in every HTML/RSC
//                                     payload.
// Run: node scripts/bake-outline-assets.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const words = JSON.parse(fs.readFileSync(path.join(root, "scripts/data/outline-words.json"), "utf8"));
const A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
const NUMS = 194; // M x y + 32 × C (6 numbers)

const parse = (d) => {
  const n = d.match(/-?\d+\.\d+/g).map((x) => Math.round(parseFloat(x) * 100));
  if (n.length !== NUMS || d.replace(/[-0-9. ]+/g, "") !== "M" + "C".repeat(32) + "Z") {
    throw new Error("unexpected path shape: " + d.slice(0, 60));
  }
  return n;
};
const fmt = (v) => (v < 0 ? "-" : "") + (Math.abs(v) / 100).toFixed(2);
const toAbs = (n) => {
  let r = "M" + fmt(n[0]) + " " + fmt(n[1]);
  for (let c = 0; c < 32; c++) r += "C" + n.slice(2 + c * 6, 8 + c * 6).map(fmt).join(" ");
  return r + "Z";
};

// ---- packed morph data -------------------------------------------------
let prev = [0, 0];
let data = "";
for (const w of words) {
  for (const drop of w.droplets) {
    for (const d of [drop.start, drop.end]) {
      const n = parse(d);
      if (toAbs(n) !== d) throw new Error("round-trip mismatch");
      n.forEach((v, k) => {
        const ax = k & 1;
        const delta = v - prev[ax];
        prev[ax] = v;
        let z = delta < 0 ? -2 * delta - 1 : 2 * delta;
        do {
          let c = z & 31;
          z = Math.floor(z / 32);
          if (z) c |= 32;
          data += A[c];
        } while (z);
      });
    }
  }
}
const meta = words.map((w) => [w.label, w.width, w.height, w.droplets.length]);
const banner = `/* Generated by scripts/bake-outline-assets.mjs. Do not edit by hand. */\n`;
fs.writeFileSync(
  path.join(root, "components/outlineMorphMeta.ts"),
  banner + `/** [label, width, height, droplet count] */\n` +
    `export const OUTLINE_META: readonly (readonly [string, number, number, number])[] = ${JSON.stringify(meta)};\n`,
);
fs.writeFileSync(
  path.join(root, "components/outlineMorphPacked.ts"),
  banner + `export const OUTLINE_PACKED = ${JSON.stringify(data)};\n`,
);

// ---- resting letters as CSS masks -----------------------------------------
const trim = (v) => {
  const r = (Math.abs(v) / 100).toFixed(2).replace(/0+$/, "").replace(/\.$/, "").replace(/^0\./, ".");
  return (v < 0 ? "-" : "") + (r === "" ? "0" : r);
};
const restingPaths = {};
let css = "/* Generated by scripts/bake-outline-assets.mjs. Do not edit by hand. */\n" +
  ".nav-word{position:relative;display:inline-flex;align-items:center;color:inherit}\n" +
  ".nav-word::before{content:\"\";position:absolute;background-color:currentColor;" +
  "-webkit-mask-image:var(--nav-word-mask);mask-image:var(--nav-word-mask);" +
  "-webkit-mask-size:100% 100%;mask-size:100% 100%;-webkit-mask-repeat:no-repeat;mask-repeat:no-repeat}\n";
for (const w of words) {
  if (w.label !== w.label[0].toUpperCase() + w.label.slice(1)) continue; // nav uses Title Case
  let minX = 0, minY = 0, maxX = w.width, maxY = w.height;
  let d = "";
  restingPaths[w.label] = [];
  for (const drop of w.droplets) {
    const n = parse(drop.start);
    for (let k = 0; k < NUMS; k += 2) {
      minX = Math.min(minX, n[k] / 100); maxX = Math.max(maxX, n[k] / 100);
      minY = Math.min(minY, n[k + 1] / 100); maxY = Math.max(maxY, n[k + 1] / 100);
    }
    let cx = n[0], cy = n[1];
    const parts = [];
    for (let c = 0; c < 32; c++) {
      const q = n.slice(2 + c * 6, 8 + c * 6);
      parts.push(q.map((v, i) => trim(v - (i & 1 ? cy : cx))).join(" "));
      cx = q[4]; cy = q[5];
    }
    // Each droplet stays its own path so overlaps paint exactly like the
    // separate <path> elements did.
    restingPaths[w.label].push(`M${trim(n[0])} ${trim(n[1])}c${parts.join(" ").replace(/ -/g, "-")}z`);
    d += `<path d='M${trim(n[0])} ${trim(n[1])}c${parts.join(" ").replace(/ -/g, "-")}z'/>`;
  }
  minX = Math.floor(minX) - 1; minY = Math.floor(minY) - 1;
  maxX = Math.ceil(maxX) + 1; maxY = Math.ceil(maxY) + 1;
  const vw = maxX - minX, vh = maxY - minY;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${vw}' height='${vh}' viewBox='${minX} ${minY} ${vw} ${vh}'>${d}</svg>`;
  css += `.nav-word-${w.label}{width:${w.width}px;height:${w.height}px}\n`;
  css += `.nav-word-${w.label}::before{left:${minX}px;top:${minY}px;width:${vw}px;height:${vh}px;` +
    `--nav-word-mask:url("data:image/svg+xml;utf8,${svg}")}\n`;
}
fs.writeFileSync(
  path.join(root, "components/outlineRestingPaths.ts"),
  banner + `/** Resting droplet outlines as compact relative paths (server only). */\n` +
    `export const RESTING_PATHS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(restingPaths)};\n`,
);
console.log("packed", data.length, "css", css.length);
