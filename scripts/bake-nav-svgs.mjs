// Bakes the resting nav letters (droplet outlines at progress 0) into static,
// content-hashed SVG files drawn with a CSS mask in currentColor, so the path
// data is cached once instead of riding in every HTML document.
//   public/nav/<label>.<hash>.svg   one file per label
//   components/navWordAssets.ts     url + box (incl. overflow padding) per label
// Run: node scripts/bake-nav-svgs.mjs
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const words = JSON.parse(fs.readFileSync(path.join(root, "scripts/data/outline-words.json"), "utf8"));
const restingSrc = fs.readFileSync(path.join(root, "components/outlineRestingPaths.ts"), "utf8");
const RESTING = JSON.parse(restingSrc.slice(restingSrc.indexOf("= ") + 2).trim().replace(/;$/, ""));
const outDir = path.join(root, "public/nav");
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const assets = {};
for (const label of ["Work", "Archive", "About"]) {
  const w = words.find((x) => x.label === label);
  const ds = w.droplets.map((d) => d.start);
  const compact = RESTING[label];
  if (compact.length !== ds.length) throw new Error("resting path count mismatch");
  // Control points bound the curves, so this box contains every pixel.
  let x0 = 0, y0 = 0, x1 = w.width, y1 = w.height;
  for (const d of ds) {
    const n = d.match(/-?\d+(\.\d+)?/g).map(Number);
    for (let i = 0; i < n.length; i += 2) {
      x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]);
      y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]);
    }
  }
  // Whole-pixel padding keeps the mask grid aligned with the inline SVG's.
  const pad = { l: Math.ceil(-x0) + 1, t: Math.ceil(-y0) + 1, r: Math.ceil(x1 - w.width) + 1, b: Math.ceil(y1 - w.height) + 1 };
  const bw = +(w.width + pad.l + pad.r).toFixed(2);
  const bh = +(w.height + pad.t + pad.b).toFixed(2);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${bw}" height="${bh}" viewBox="${-pad.l} ${-pad.t} ${bw} ${bh}"><g id="w">` +
    compact.map((d) => `<path d="${d}"/>`).join("") + `</g></svg>`;
  const hash = crypto.createHash("sha256").update(svg).digest("hex").slice(0, 10);
  const file = `${label.toLowerCase()}.${hash}.svg`;
  fs.writeFileSync(path.join(outDir, file), svg);
  assets[label] = { url: `/nav/${file}`, width: w.width, height: w.height, pad, boxWidth: bw, boxHeight: bh };
}
fs.writeFileSync(
  path.join(root, "components/navWordAssets.ts"),
  `/* Generated by scripts/bake-nav-svgs.mjs. Do not edit by hand. */\n` +
    `export const NAV_WORD_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`,
);
console.log(assets);
